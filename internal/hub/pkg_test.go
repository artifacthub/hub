package hub

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestPackageCategoryFromName(t *testing.T) {
	t.Parallel()

	testCases := []struct {
		name             string
		expectedCategory PackageCategory
		expectedErr      string
	}{
		{"skip-prediction", SkipCategoryPrediction, ""},
		{"ai-machine-learning", PackageCategory(1), ""},
		{"security", PackageCategory(6), ""},
		{"streaming-messaging", PackageCategory(8), ""},
		{"analytics", PackageCategory(9), ""},
		{"data-processing", PackageCategory(10), ""},
		{"web-applications", PackageCategory(11), ""},
		{"none", PackageCategory(-9), "invalid category name"},
		{"", PackageCategory(-9), "invalid category name"},
		{"Security", PackageCategory(-9), "invalid category name"},
		{"invalid", PackageCategory(-9), "invalid category name"},
	}
	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			category, err := PackageCategoryFromName(tc.name)
			assert.Equal(t, tc.expectedCategory, category)
			if tc.expectedErr == "" {
				assert.NoError(t, err)
			} else {
				assert.EqualError(t, err, tc.expectedErr)
			}
		})
	}
}

func TestPackageSetAutoGeneratedDigest(t *testing.T) {
	t.Parallel()

	t.Run("category source does not affect the digest", func(t *testing.T) {
		t.Parallel()

		p1 := &Package{Name: "pkg1", Version: "1.0.0", Category: PackageCategory(6)}
		require.NoError(t, p1.SetAutoGeneratedDigest())
		p2 := &Package{
			Name:           "pkg1",
			Version:        "1.0.0",
			Category:       PackageCategory(6),
			CategorySource: PackageCategorySourcePublisher,
		}
		require.NoError(t, p2.SetAutoGeneratedDigest())
		assert.NotEmpty(t, p1.Digest)
		assert.Equal(t, p1.Digest, p2.Digest)
	})

	t.Run("category display name does not affect the digest", func(t *testing.T) {
		t.Parallel()

		p1 := &Package{Name: "pkg1", Version: "1.0.0", Category: PackageCategory(6)}
		require.NoError(t, p1.SetAutoGeneratedDigest())
		p2 := &Package{
			Name:                "pkg1",
			Version:             "1.0.0",
			Category:            PackageCategory(6),
			CategoryDisplayName: "Security",
		}
		require.NoError(t, p2.SetAutoGeneratedDigest())
		assert.NotEmpty(t, p1.Digest)
		assert.Equal(t, p1.Digest, p2.Digest)
	})

	t.Run("category affects the digest", func(t *testing.T) {
		t.Parallel()

		p1 := &Package{Name: "pkg1", Version: "1.0.0", Category: PackageCategory(6)}
		require.NoError(t, p1.SetAutoGeneratedDigest())
		p2 := &Package{Name: "pkg1", Version: "1.0.0", Category: PackageCategory(7)}
		require.NoError(t, p2.SetAutoGeneratedDigest())
		assert.NotEqual(t, p1.Digest, p2.Digest)
	})
}
